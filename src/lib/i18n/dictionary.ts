const DICTS: Record<Lang, Record<DictKey, string>> = { en, hi };

export function t(lang: Lang, key: DictKey): string {
  return DICTS[lang][key] ?? en[key];
}

export function errorText(lang: Lang, code: string | undefined): string {
  const k = `err_${code}` as DictKey;
  return k in en ? t(lang, k) : t(lang, "err_GENERIC");
}

/**
 * Bilingual content with fallback: the requested language if present,
 * otherwise the other one. `fallback` tells the UI to show a notice.
 */
export function pickText(lang: Lang, textEn: string | null | undefined, textHi: string | null | undefined) {
  if (lang === "hi") return textHi ? { text: textHi, fallback: false } : { text: textEn ?? "", fallback: !!textEn };
  return textEn ? { text: textEn, fallback: false } : { text: textHi ?? "", fallback: !!textHi };
}

export function normalizeLang(v: string | null | undefined): Lang {
  return v === "hi" ? "hi" : "en";
}

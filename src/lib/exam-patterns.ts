/**
 * Library of Indian competitive-exam patterns used by the admin
 * "Create from pattern" tool. Creating an exam from a pattern fills in the
 * title, category, total duration, sections, marks and negative marking; the
 * admin then attaches questions and can edit everything.
 *
 * ACCURACY RULES
 *  - `verified: true` only where the pattern matches the latest official
 *    notification known to us. Everything else is marked "not verified" in the
 *    admin UI and in the generated instructions — check the current
 *    notification before publishing.
 *  - Sectional timing is recorded per pattern (`timing`) and never inferred
 *    from the total duration. Sections that share one timer share a
 *    `timerGroup`; `groupMinutes` is that timer's length.
 *  - Patterns change between recruitment years: `patternYear` says which
 *    notification the numbers come from.
 */

export type TimingType =
  /** Type A: each section has its own fixed timer; time cannot be moved between sections. */
  | "SECTIONAL"
  /** Type B: one timer for the whole paper. */
  | "OVERALL"
  /** Type C: separately timed papers/modules (subjects inside a module share its timer). */
  | "MODULES"
  /** Type D: not confirmed by an official source. */
  | "NOT_VERIFIED";

export type PatternSection = {
  code: string;
  titleEn: string;
  titleHi?: string;
  subject: string;
  questions: number;
  marksCorrect: number;
  /** Positive magnitude deducted for a wrong answer (0 = no negative marking). */
  marksWrong: number;
  /** Sections with the same group share one timer (SECTIONAL / MODULES patterns). */
  timerGroup?: string;
  groupMinutes?: number;
  /** Qualifying-only section (marks not counted for merit). */
  qualifying?: boolean;
};

export type ExamGroup = "SSC" | "BANKING" | "RAILWAY" | "TEACHING" | "UPSC" | "STATE_PSC" | "DEFENCE" | "POLICE" | "INSURANCE" | "GOVT_OTHER";

export type ExamPattern = {
  id: string;
  group: ExamGroup;
  /** Category the created test is listed under (created on first use). */
  category: { slug: string; nameEn: string; nameHi: string };
  nameEn: string;
  nameHi: string;
  stage: string;
  authority: string;
  durationMinutes: number;
  timing: TimingType;
  timingNote?: string;
  sections: PatternSection[];
  /** Official website / notification page. */
  source: string;
  patternYear: string;
  verified: boolean;
  notes?: string;
};


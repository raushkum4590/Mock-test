export type LibraryCategory = { group: ExamGroup; slug: string; nameEn: string; nameHi: string; patterns: ExamPattern[] };

/** Exam categories of the library in group order (used for site navigation and category pages). */
export function libraryCategories(): LibraryCategory[] {
  const bySlug = new Map<string, LibraryCategory>();
  for (const p of EXAM_PATTERNS) {
    const c = bySlug.get(p.category.slug) ?? { group: p.group, ...p.category, patterns: [] };
    c.patterns.push(p);
    bySlug.set(p.category.slug, c);
  }
  const order = Object.keys(GROUP_LABELS) as ExamGroup[];
  return [...bySlug.values()].sort((a, b) => order.indexOf(a.group) - order.indexOf(b.group));
}

export function findLibraryCategory(slug: string): LibraryCategory | undefined {
  return libraryCategories().find((c) => c.slug === slug);
}

export function findPattern(id: string): ExamPattern | undefined {
  return EXAM_PATTERNS.find((p) => p.id === id);
}

export function patternTotals(p: ExamPattern) {
  return {
    questions: p.sections.reduce((n, s) => n + s.questions, 0),
    marks: Math.round(p.sections.reduce((n, s) => n + s.questions * s.marksCorrect, 0) * 100) / 100,
  };
}

export const TIMING_LABELS: Record<TimingType, string> = {
  SECTIONAL: "Fixed sectional timing",
  OVERALL: "Overall timer only",
  MODULES: "Separately timed modules / papers",
  NOT_VERIFIED: "Sectional timing not verified",
};

/** Candidate-facing instructions generated for a test created from a pattern. */
export function patternInstructions(p: ExamPattern): { en: string; hi: string } {
  const t = patternTotals(p);
  const lines = p.sections.map((s) => {
    const neg = s.marksWrong > 0 ? `−${s.marksWrong}` : "no negative marking";
    const time = s.groupMinutes ? `, ${s.groupMinutes} min (timer group ${s.timerGroup})` : "";
    return `- ${s.titleEn}: ${s.questions} questions, +${s.marksCorrect} / ${neg}${time}${s.qualifying ? " — qualifying" : ""}`;
  });
  const en = [
    `${p.nameEn} — ${p.stage}`,
    `Total: ${t.questions} questions, ${t.marks} marks, ${p.durationMinutes} minutes.`,
    `Timing: ${TIMING_LABELS[p.timing]}.${p.timingNote ? ` ${p.timingNote}` : ""}`,
    "",
    ...lines,
    "",
    p.notes ?? "",
    `Pattern source: ${p.source} (${p.patternYear}${p.verified ? "" : ", not verified — check the latest official notification"}).`,
  ]
    .filter((l, i, a) => l !== "" || a[i - 1] !== "")
    .join("\n");
  const hi = [
    `${p.nameHi} — कुल ${t.questions} प्रश्न, ${t.marks} अंक, ${p.durationMinutes} मिनट।`,
    ...p.sections.map((s) => `- ${s.titleHi ?? s.titleEn}: ${s.questions} प्रश्न, +${s.marksCorrect}${s.marksWrong > 0 ? ` / −${s.marksWrong}` : " (कोई ऋणात्मक अंकन नहीं)"}`),
    `स्रोत: ${p.source}${p.verified ? "" : " (सत्यापित नहीं — नवीनतम आधिकारिक अधिसूचना देखें)"}`,
  ].join("\n");
  return { en, hi };
}

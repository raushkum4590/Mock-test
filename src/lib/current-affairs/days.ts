const norm = (day: string) =>
  day
    .toLowerCase()
    .replace(/[’']/g, "")
    .replace(/\s+20\d\d$/, "")
    .replace(/\s+/g, " ")
    .trim();

/** The fixed observance date of a day ("16 October"), or null if not in the table. */
export function fixedDayDate(day: string): string | null {
  return FIXED[norm(day)] ?? null;
}

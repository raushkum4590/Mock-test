const NAMES = Object.keys(COUNTRIES).sort((a, b) => b.length - a.length);
const COUNTRY_RE = new RegExp(`\\b(${NAMES.map((n) => n.replace(/ /g, "\\s+")).join("|")})\\b`, "g");

/** Countries (other than India) mentioned in a text, in order of appearance, de-duplicated. */
export function countriesIn(text: string): string[] {
  const out: string[] = [];
  for (const m of text.matchAll(COUNTRY_RE)) {
    const c = COUNTRIES[m[1]!.replace(/\s+/g, " ")];
    if (c && !out.includes(c)) out.push(c);
  }
  return out;
}

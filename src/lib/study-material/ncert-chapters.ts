const BY_CODE = new Map<string, { book: NcertBook; medium: "en" | "hi" }>();
for (const book of NCERT_BOOKS) {
  if (book.en) BY_CODE.set(book.en.code, { book, medium: "en" });
  if (book.hi) BY_CODE.set(book.hi.code, { book, medium: "hi" });
}

/** Chapter title (1-based) in the edition's own language, or null when unknown. */
export function chapterTitle(code: string, chapter: number): string | null {
  const found = BY_CODE.get(code);
  if (!found) return null;
  const titles = NCERT_CHAPTERS[found.book.id];
  const edition = found.book[found.medium]!;
  if (!titles || titles.length !== edition.chapters) return null;
  return titles[chapter - 1]?.[found.medium === "en" ? 0 : 1] ?? null;
}

function tableQs(r: Rng, rows: [string, string][], key: string, topic: string, text: (p: string) => string): (GenQuestion | null)[] {
  const data = rows.map(([p, a]) => ({ p, a }));
  return data.map((row) =>
    factQuestion(r, data, row, { key: (x) => `H:${key}:${x.p}`, subject: S, topic, en: (x) => text(x.p), hi: (x) => text(x.p), answer: (x) => x.a }),
  );
}

export function allHindiQuestions(r: Rng): GenQuestion[] {
  const out: (GenQuestion | null)[] = [
    ...tableQs(r, PARYAY, "paryay", "पर्यायवाची", (p) => `'${p}' का पर्यायवाची शब्द कौन-सा है?`),
    ...tableQs(r, VILOM, "vilom", "विलोम", (p) => `'${p}' का विलोम शब्द कौन-सा है?`),
    ...tableQs(r, EK_SHABD, "ek", "वाक्यांश के लिए एक शब्द", (p) => `'${p}' के लिए एक शब्द है:`),
    ...tableQs(r, MUHAVARE, "muhavara", "मुहावरे", (p) => `मुहावरे '${p}' का अर्थ है:`),
    ...tableQs(r, TADBHAV, "tadbhav", "तत्सम-तद्भव", (p) => `तत्सम शब्द '${p}' का तद्भव रूप क्या है?`),
    ...SANDHI.map(([w, a, wrong]) => mcq(r, { key: `H:sandhi:${w}`, subject: S, topic: "संधि", difficulty: "MEDIUM", en: `'${w}' का सही संधि-विच्छेद है:`, hi: `'${w}' का सही संधि-विच्छेद है:` }, a, wrong)),
  ];
  return out.filter((x): x is GenQuestion => !!x);
}

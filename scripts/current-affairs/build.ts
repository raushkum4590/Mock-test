/**
 * Builds the Current Affairs Capsule data from the downloaded headlines:
 * data/current-affairs/raw/YYYY-MM.json  ->  src/data/current-affairs/YYYY-MM.json
 * plus src/data/current-affairs/index.ts (static imports, newest month first).
 *
 *   npx tsx scripts/current-affairs/build.ts
 *
 * Run backfill.ts first. Distractors for the quizzes come from the whole
 * year, so always rebuild all months together.
 */
import fs from "node:fs";
import path from "node:path";
import type { CapsuleMonth } from "../../src/lib/current-affairs/capsule";
import { extractMonth, type MonthFacts, type RawItem, type Source } from "../../src/lib/current-affairs/extract";
import { buildPools, buildQuiz, monthLabel } from "../../src/lib/current-affairs/quiz";

const RAW = path.join(process.cwd(), "data", "current-affairs", "raw");
const OUT = path.join(process.cwd(), "src", "data", "current-affairs");

function main() {
  const files = fs
    .readdirSync(RAW)
    .filter((f) => /^\d{4}-\d{2}\.json$/.test(f))
    .sort();
  if (!files.length) throw new Error("No months in data/current-affairs/raw — run backfill.ts first.");

  const now = new Date();
  const current = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}`;
  const months: { ym: string; raw: RawItem[]; facts: MonthFacts }[] = files.map((f) => {
    const raw = JSON.parse(fs.readFileSync(path.join(RAW, f), "utf8")) as RawItem[];
    return { ym: f.slice(0, 7), raw, facts: extractMonth(raw) };
  });
  const pools = buildPools(months.map((m) => m.facts));

  fs.mkdirSync(OUT, { recursive: true });
  for (const f of fs.readdirSync(OUT)) if (/^\d{4}-\d{2}\.json$/.test(f)) fs.rmSync(path.join(OUT, f));

  for (const m of months) {
    const headlines = { PIB: 0, RBI: 0, AIR: 0 } as Record<Source, number>;
    for (const i of m.raw) headlines[i.source]++;
    const capsule: CapsuleMonth = {
      month: m.ym,
      label: monthLabel(m.ym),
      partial: m.ym >= current,
      generatedAt: now.toISOString(),
      headlines,
      facts: m.facts,
      quiz: buildQuiz(m.ym, m.facts, pools),
    };
    fs.writeFileSync(path.join(OUT, `${m.ym}.json`), JSON.stringify(capsule));
    const f = m.facts;
    console.log(
      `${m.ym}: ${m.raw.length} headlines -> appointments ${f.appointments.length}, exercises ${f.exercises.length}, awards ${f.awards.length}, days ${f.days.length}, ` +
        `summits ${f.summits.length}, MoUs ${f.agreements.length}, sports ${f.sports.length}, launches ${f.launches.length}, cabinet ${f.cabinet.length}, ` +
        `one-liners ${f.oneLiners.length}, quiz ${capsule.quiz.length}`,
    );
  }

  const ids = months.map((m) => m.ym).reverse();
  const ident = (ym: string) => `m${ym.replace("-", "_")}`;
  fs.writeFileSync(
    path.join(OUT, "index.ts"),
    [
      "// Generated by scripts/current-affairs/build.ts — do not edit by hand.",
      'import type { CapsuleMonth } from "@/lib/current-affairs/capsule";',
      ...ids.map((ym) => `import ${ident(ym)} from "./${ym}.json";`),
      "",
      "/** Newest month first. */",
      `export const CAPSULE_MONTHS = [${ids.map(ident).join(", ")}] as unknown as CapsuleMonth[];`,
      "",
    ].join("\n"),
  );
  console.log(`Wrote ${months.length} months to src/data/current-affairs/`);
}

main();
